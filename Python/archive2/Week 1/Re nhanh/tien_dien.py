N = int(input())
A = N * 550 
a = A // 10
B = 55000 + (N - 100) * 900
b = B // 10
C = 55000 + 45000 + (N - 100 - 50) * 1250
c = C // 10
D = 55000 + 45000 + 62500 + (N - 100 - 50 - 50) * 1450
d = D // 10
E = 55000 + 45000 + 62500 + 145000 + (N - 100 - 50 - 50 - 100) * 1700
e = E // 10

if N <= 100:
    print(A + a)
elif N <= 150:
    print(B + b)
elif N <= 200:
    print(C + c)
elif N <= 300:
    print(D + d)
else:
    print(E + e)